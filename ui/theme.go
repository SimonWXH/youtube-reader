// Architecture decision (MyGo v0.10.0): there is no public dynamic semantic
// colour API. ui.Color holds sRGB bytes; MyGo snapshots
// NSColor.controlAccentColor into ui.Preferences.Accent and Increase Contrast
// into Preferences.HighContrast, which its own default theme follows, but it
// exposes no NSColor object, dynamic-colour constructor, or resolved values
// for labelColor, secondaryLabelColor, separatorColor,
// selectedContentBackgroundColor, windowBackgroundColor or
// keyboardFocusIndicatorColor. The internal AppKit calls are not importable.
// This hex ramp is the design board's own palette for chrome and content, so
// these Tokens carry no system accent and no native increased-contrast
// response: taking the available accent/contrast snapshots into the board's
// fixed colours would change the agreed appearance and its documentation,
// outside this file. Connecting the missing semantic colours would need a
// native module or a framework change.

// Motion durations. Every animation in the app uses Ease, the one shared
// cubic-bezier(.22, 1, .36, 1) curve. Under Reduce Motion MyGo skips movement
// and width transitions but keeps colour transitions smooth.
const (
	// MotionInteraction is hover, press, and selection colour changes.
	MotionInteraction = 120 * time.Millisecond
	// MotionPopover is a popover or overflow menu appearing and resizing.
	MotionPopover = 180 * time.Millisecond
	// MotionLayout is the detail pane's width-only open and close.
	MotionLayout = 240 * time.Millisecond
)

// Ease is the app's only motion curve.
var Ease = ui.CubicBezier(0.22, 1, 0.36, 1)

// Fade is the colour transition shared by buttons, rows, and cards. MyGo
// keeps colour transitions smooth under Reduce Motion.
var Fade = ui.ElementTransition{
	Duration: MotionInteraction,
	Ease:     Ease,
	Colors:   true,
}

// Layout is the detail pane's open and close transition: width only, so the
// grid reflows between frames. The framework makes it instant under Reduce
// Motion.
var Layout = ui.ElementTransition{
	Duration: MotionLayout,
	Ease:     Ease,
	Width:    true,
}

// Tokens are the single source of truth for surface, text, and accent colors.
// Values are tuned per appearance rather than generated by inversion. Each
// field names one role so surfaces consume a token instead of a literal color.
type Tokens struct {
	App        ui.Color // App is the content and detail background.
	Sidebar    ui.Color // Sidebar is the navigation column behind its rows.
	Surface    ui.Color // Surface is cards, inputs, and popover panels.
	SurfaceAlt ui.Color // SurfaceAlt is one step lower: hover, disabled, segmented slots.
	Border     ui.Color // Border is a 1 pt panel rule and control outline.
	BorderSoft ui.Color // BorderSoft is the lighter card outline and in-group rule.
	Text       ui.Color // Text is body copy and titles.
	Muted      ui.Color // Muted is secondary copy and metadata.
	Faint      ui.Color // Faint is the disabled-state label only: in light it clears 4.5:1 on a flat Surface but not on SurfaceAlt, the sidebar, or the app background, while in dark it passes on all of them, so secondary and metadata text uses Muted.
	Accent     ui.Color // Accent is the only highlight: primary fill, selection, links, the unwatched dot.
	AccentText ui.Color // AccentText sits on an Accent fill.
	AccentSoft ui.Color // AccentSoft is the selected-row and segmented-control fill.
	Danger     ui.Color // Danger is destructive actions and failure copy, always with an icon or words.
	Warning    ui.Color // Warning is quota-paused and offline notices.
	Success    ui.Color // Success is the up-to-date mark.
	Focus      ui.Color // Focus draws the 2 pt ring.
	Shadow     ui.Color // Shadow is a legacy shadow ink; the L1 popover ink is specified with the elevation geometry.
	// ModalScrim is the L2 backdrop over the window behind an in-window
	// modal panel. It is ink, not a surface: a modal never replaces the
	// window's surfaces with an opaque colour.
	ModalScrim ui.Color
	// ModalShadow is the L2 panel's shadow ink, drawn with the
	// ElevationModal geometry below.
	ModalShadow ui.Color
	// The workspace dock's active glyph keeps its own brand colour while the
	// three unselected glyphs step back to WorkspaceDockIdle; hover and press
	// draw a 1 pt outline so no state dims or covers the ink with a plate.
	// Dark mode lifts the warm inks while RSS keeps #2bb24c in both
	// appearances.
	WorkspaceVideo     ui.Color // WorkspaceVideo is the Video dock glyph.
	WorkspaceRSS       ui.Color // WorkspaceRSS is the RSS dock glyph.
	WorkspaceReadLater ui.Color // WorkspaceReadLater is the 稍后读 dock glyph.
	WorkspaceWeChat    ui.Color // WorkspaceWeChat is the 微信读书 dock glyph.
	// WorkspaceDockIdle is the muted colour of an unselected dock glyph.
	WorkspaceDockIdle ui.Color
	// WorkspaceDockHoverOutline marks the dock slot under the pointer: a
	// 1 pt outline that reads on the sidebar without tinting any ink.
	WorkspaceDockHoverOutline ui.Color
}

