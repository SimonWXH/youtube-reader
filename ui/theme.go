// Space maps to the app's 4 pt baseline grid.
func Space(n float32) float32 { return 4 * n }

// Spacing steps. Every gap, padding, and margin sits on this 4 pt ladder; the
// role names say where each step belongs.
const (
	SpaceInline  float32 = 4  // icon to label, and within a tightly bound pair
	SpaceTight   float32 = 8  // between buttons, toolbar icons, and form fields
	SpaceItem    float32 = 12 // between items inside one group or panel
	SpacePanel   float32 = 16 // panel padding and the gap between groups
	SpaceSection float32 = 20 // between blocks in the detail pane
	SpaceBlock   float32 = 24 // between settings groups
	SpaceMargin  float32 = 32 // window and empty-state margins
	SpaceLarge   float32 = 40 // a large block, used sparingly
	SpaceWide    float32 = 48 // the widest rhythm step
)

// Radii. Corners never leave these five values; avatars alone use a 50% circle.
const (
	RadiusCheck   float32 = 3  // check boxes and tiny marks
	RadiusControl float32 = 6  // buttons, inputs, selects, and sidebar rows
	RadiusNotice  float32 = 8  // inline notices and thumbnail placeholders
	RadiusCard    float32 = 10 // cards, thumbnails, and detail media
	RadiusWindow  float32 = 12 // windows and popovers
)

// Hairline and focus widths. Rules are 1 pt, a selection outline is 1 pt, and
// the focus ring is a 2 pt line set 3 pt outside the control.
const (
	Hairline     float32 = 1
	FocusRing    float32 = 2
	FocusRingGap float32 = 3
)

// ShadowStyle is the app's one raised-surface shadow geometry. Cards, rows,
// and forms stay flat (L0); only popovers and overflow menus are raised (L1);
// modal alerts are drawn by the system (L2).
type ShadowStyle struct {
	OffsetY float32
	Blur    float32
	Spread  float32
}

// Elevation is the single L1 shadow, drawn with the token's Shadow ink.
var Elevation = ShadowStyle{OffsetY: 14, Blur: 34, Spread: -10}

// Apply draws the elevation on el with the token's Shadow ink.
func (s ShadowStyle) Apply(el ui.Element, ink ui.Color) ui.Element {
	return el.Shadow(0, s.OffsetY, s.Blur, s.Spread, ink)
}

// State is one of the eight defined interactive states.
type State uint8

const (
	Default State = iota
	Hover
	Focus
	Active
	Disabled
	Loading
	Error
	Success
)

// ControlFace describes the visual treatment of an interactive element.
type ControlFace struct {
	Background ui.Color
	Border     ui.Color
	Text       ui.Color
}

// Face returns the token-driven appearance for one control state.
// "Quiet" controls (toolbar, sidebar rows) stay neutral except for focus and
// the active selection, while primary controls reserve the accent color.
func (t Tokens) Face(state State, primary, quiet bool) ControlFace {
	switch {
	case state == Disabled:
		return ControlFace{t.SurfaceAlt, t.BorderSoft, t.Faint}
	case state == Loading:
		return ControlFace{t.SurfaceAlt, t.Border, t.Muted}
	case state == Error:
		return ControlFace{t.SurfaceAlt, t.Danger.Alpha(0.45), t.Danger}
	case state == Success:
		return ControlFace{t.SurfaceAlt, t.Success.Alpha(0.45), t.Success}
	case state == Focus:
		f := ControlFace{t.Surface, t.Focus, t.Text}
		if primary {
			f.Background, f.Border, f.Text = t.Accent, t.Focus, t.AccentText
		}
		return f
	case state == Active:
		if primary {
			return ControlFace{t.Accent.Mix(t.Text, 0.12), t.Accent, t.AccentText}
		}
		if quiet {
			return ControlFace{t.AccentSoft, t.AccentSoft, t.Accent}
		}
		return ControlFace{t.AccentSoft, t.Accent, t.Accent}
	case state == Hover:
		if primary {
			return ControlFace{t.Accent.Mix(t.Surface, 0.12), t.Accent, t.AccentText}
		}
		return ControlFace{t.SurfaceAlt, t.Border, t.Text}
	default:
		if primary {
			return ControlFace{t.Accent, t.Accent, t.AccentText}
		}
		if quiet {
			return ControlFace{t.Sidebar, t.Sidebar, t.Text}
		}
		return ControlFace{t.Surface, t.Border, t.Text}
	}
}
