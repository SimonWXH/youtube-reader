// Space maps to the app's 4 pt baseline grid: 4 inline, 8 tight, 12 item,
// 16 panel, 20 section, 24 block, 32 margin, 40 large, 48 wide. New work uses
// only these steps.
func Space(n float32) float32 { return 4 * n }

// Radii. New work keeps corners to these five values. The 50% circles in the
// tree are avatars and the unwatched dot, and are the only exceptions.
const (
	RadiusCheck   float32 = 3  // check boxes and tiny marks
	RadiusControl float32 = 6  // buttons, inputs, selects, and sidebar rows
	RadiusNotice  float32 = 8  // inline notices
	RadiusCard    float32 = 10 // cards, thumbnails, and detail media
	RadiusWindow  float32 = 12 // windows and popovers
)

// Hairline and focus widths. Rules and the grid-card selection stroke are 1 pt.
// The grid card adds a 2 pt 24% accent halo outside that stroke and sets the
// 2 pt keyboard focus ring FocusRingGap outside the card. Sidebar rows set the
// same 2 pt ring 3 pt outside their bounds, while StatefulButton still draws
// only the 1 pt stroke and passes a 2 pt focus offset. Sidebar rows and
// segmented controls show selection as a tinted background with accent text.
const (
	Hairline     float32 = 1
	FocusRing    float32 = 2
	FocusRingGap float32 = 3
)

// Elevation. Cards, rows, and forms stay flat (L0); only popovers and overflow
// menus are raised (L1) with offset 14 pt, blur 34 pt, spread -10 pt. L2 is the
// in-window modal panel: macOS draws a system alert, but a panel the app draws
// itself over the window - the add-subscription dialog, and every modal that
// follows it - is a surface at Modal elevation over Tokens.ModalScrim. The L1
// shadow ink is owned by design board B3 and must be painted exactly as: light
// 0 0 0 0.5px rgba(0,0,0,.12) plus 0 14px 34px -10px rgba(24,26,28,.28); dark
// 0 0 0 0.5px rgba(0,0,0,.5) plus 0 14px 34px -10px rgba(0,0,0,.65); with a
// 0.5 pt stroke. Tokens.Shadow is not the L1 ink.
const (
	ElevationOffsetY float32 = 14
	ElevationBlur    float32 = 34
	ElevationSpread  float32 = -10
	// The L2 panel rises higher than a popover so that it separates from
	// the scrimmed window it covers, and keeps a wider spread so its ink
	// spreads into the scrim instead of ending in a hard band.
	ElevationModalOffsetY float32 = 24
	ElevationModalBlur    float32 = 48
	ElevationModalSpread  float32 = -12
)

// State is one of the eight defined interactive states.
type State uint8

const (
	Default State = iota
	Hover
	Focus
	Active
	Disabled
	Loading
	Error
	Success
)

// ControlFace describes the visual treatment of an interactive element.
type ControlFace struct {
	Background ui.Color
	Border     ui.Color
	Text       ui.Color
}

// Face returns the token-driven appearance for one control state.
// "Quiet" controls (toolbar, sidebar rows) stay neutral except for focus and
// the active selection, while primary controls reserve the accent color.
func (t Tokens) Face(state State, primary, quiet bool) ControlFace {
	switch {
	case state == Disabled:
		return ControlFace{t.SurfaceAlt, t.Border, t.Faint}
	case state == Loading:
		return ControlFace{t.SurfaceAlt, t.Border, t.Muted}
	case state == Error:
		return ControlFace{t.SurfaceAlt, t.Danger.Alpha(0.45), t.Danger}
	case state == Success:
		return ControlFace{t.SurfaceAlt, t.Success.Alpha(0.45), t.Success}
	case state == Focus:
		f := ControlFace{t.Surface, t.Focus, t.Text}
		if primary {
			f.Background, f.Border, f.Text = t.Accent, t.Focus, t.AccentText
		}
		return f
	case state == Active:
		if primary {
			return ControlFace{t.Accent.Mix(t.Text, 0.12), t.Accent, t.AccentText}
		}
		if quiet {
			return ControlFace{t.AccentSoft, t.AccentSoft, t.Accent}
		}
		return ControlFace{t.AccentSoft, t.Accent, t.Accent}
	case state == Hover:
		if primary {
			return ControlFace{t.Accent.Mix(t.Surface, 0.12), t.Accent, t.AccentText}
		}
		return ControlFace{t.SurfaceAlt, t.Border, t.Text}
	default:
		if primary {
			return ControlFace{t.Accent, t.Accent, t.AccentText}
		}
		if quiet {
			return ControlFace{t.Sidebar, t.Sidebar, t.Text}
		}
		return ControlFace{t.Surface, t.Border, t.Text}
	}
}
